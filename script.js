document.addEventListener('DOMContentLoaded', () => {
  /* ==========================================================================
   * 1. RENDER NEWSROOM ARTICLES (BOTH OVERLAY & STANDALONE NEWSROOM.HTML)
   * ========================================================================== */
  const renderArticlesInto = (container) => {
    if (!container) return;
    container.innerHTML = NEWSROOM_ARTICLES.map((article) => `
      <a href="#article" class="article clickable" data-article-id="${article.id}">
        <div class="cover" style="background-image: url('${article.coverImage}');"></div>
        <div class="title">${article.title}</div>
        <div class="subtitle">${article.subtitle}</div>
        <div class="published-at">${article.publishedAt}</div>
      </a>
    `).join('');
  };

  renderArticlesInto(document.getElementById('overlayArticlesGrid'));
  renderArticlesInto(document.getElementById('standaloneArticlesGrid'));

  /* ==========================================================================
   * 2. OVERLAY CONTROLLER (SUPPORTING STACKED OVERLAYS & SCROLL REVEAL)
   * ========================================================================== */
  const allOverlays = document.querySelectorAll('.full-screen-overlay');

  const triggerOverlayReveals = (overlayEl) => {
    const revealItems = overlayEl.querySelectorAll('.reveal-item');
    revealItems.forEach((item, index) => {
      setTimeout(() => {
        item.classList.add('is-visible');
      }, 60 * index);
    });
  };

  const openOverlayById = (overlayId) => {
    const target = document.getElementById(overlayId);
    if (!target) return;

    allOverlays.forEach((ov) => {
      if (ov !== target) {
        ov.classList.remove('active');
        ov.setAttribute('aria-hidden', 'true');
      }
    });

    target.classList.add('active');
    target.setAttribute('aria-hidden', 'false');
    document.body.classList.add('no-scroll');

    const scrollContainer = target.querySelector('.scroll-content');
    if (scrollContainer) {
      scrollContainer.scrollTop = 0;
    }

    triggerOverlayReveals(target);
  };

  const closeAllOverlays = () => {
    allOverlays.forEach((ov) => {
      ov.classList.remove('active');
      ov.setAttribute('aria-hidden', 'true');
    });
    document.body.classList.remove('no-scroll');
  };

  // Delegate overlay triggers
  document.addEventListener('click', (e) => {
    // 1. Check if user clicked an article card
    const articleCard = e.target.closest('[data-article-id]');
    if (articleCard) {
      e.preventDefault();
      const articleId = articleCard.getAttribute('data-article-id');
      const article = NEWSROOM_ARTICLES.find((a) => a.id === articleId);
      if (article) {
        const coverEl = document.getElementById('articleReaderCover');
        const titleEl = document.getElementById('articleReaderTitle');
        const subtitleEl = document.getElementById('articleReaderSubtitle');
        const contentEl = document.getElementById('articleReaderContent');
        const galleryEl = document.getElementById('articleReaderGallery');

        if (coverEl) coverEl.style.backgroundImage = `url('${article.coverImage}')`;
        if (titleEl) titleEl.textContent = article.title;
        if (subtitleEl) subtitleEl.textContent = article.subtitle;
        if (contentEl) {
          contentEl.innerHTML = article.content.map((p) => `<p>${p}</p>`).join('');
        }
        if (galleryEl) {
          galleryEl.innerHTML = (article.gallery || [])
            .map((imgUrl) => `<img src="${imgUrl}" alt="${article.title}" loading="lazy">`)
            .join('');
        }
        openOverlayById('overlay-article');
      }
      return;
    }

    // 2. Check if user clicked a model selector for the configurator
    const modelSelector = e.target.closest('[data-select-model]');
    if (modelSelector) {
      const selectedModel = modelSelector.getAttribute('data-select-model');
      updateConfiguratorModel(selectedModel);
    }

    // 3. Check if user clicked any [data-open-overlay] trigger
    const openBtn = e.target.closest('[data-open-overlay]');
    if (openBtn) {
      e.preventDefault();
      const targetOverlayId = openBtn.getAttribute('data-open-overlay');
      openOverlayById(targetOverlayId);
      return;
    }

    // 4. Check if user clicked a [data-close-overlay] trigger
    const closeBtn = e.target.closest('[data-close-overlay]');
    if (closeBtn) {
      e.preventDefault();
      closeAllOverlays();
    }
  });

  // Escape key closes active overlay
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      closeAllOverlays();
    }
  });

  /* ==========================================================================
   * 3. FULLPAGE RIGHT-SIDE NAVIGATION & SCROLL SPY (DESKTOP + MOBILE BARS)
   * ========================================================================== */
  const heroSections = document.querySelectorAll('section.hero-section[id]');
  const sideNavLinks = document.querySelectorAll('nav.side-nav .section[data-section]');

  if (heroSections.length > 0 && sideNavLinks.length > 0) {
    const sectionObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            const id = entry.target.getAttribute('id');
            sideNavLinks.forEach((link) => {
              link.classList.toggle('current', link.getAttribute('data-section') === id);
            });
          }
        });
      },
      {
        root: null,
        threshold: 0.45
      }
    );

    heroSections.forEach((sec) => sectionObserver.observe(sec));

    sideNavLinks.forEach((link) => {
      link.addEventListener('click', (e) => {
        e.preventDefault();
        const targetId = link.getAttribute('data-section');
        const targetSec = document.getElementById(targetId);
        if (targetSec) {
          closeAllOverlays();
          targetSec.scrollIntoView({ behavior: 'smooth' });
        }
      });
    });
  }

  /* ==========================================================================
   * 4. HORIZONTAL FULL-WIDTH GALLERIES (.gallery[data-gallery] + TOUCH SWIPE)
   * ========================================================================== */
  const galleries = document.querySelectorAll('.gallery[data-gallery]');

  galleries.forEach((gallery) => {
    const imagesCt = gallery.querySelector('.images-ct');
    const slides = imagesCt ? imagesCt.querySelectorAll('img') : [];
    const prevBtn = gallery.querySelector('[data-gallery-prev]');
    const nextBtn = gallery.querySelector('[data-gallery-next]');
    let currentIndex = 0;

    if (!imagesCt || slides.length === 0) return;

    const updateGallery = () => {
      imagesCt.style.transform = `translateX(-${currentIndex * 100}%)`;
      if (prevBtn) {
        prevBtn.classList.toggle('disabled', currentIndex <= 0);
      }
      if (nextBtn) {
        nextBtn.classList.toggle('disabled', currentIndex >= slides.length - 1);
      }
    };

    if (prevBtn) {
      prevBtn.addEventListener('click', () => {
        if (currentIndex > 0) {
          currentIndex -= 1;
          updateGallery();
        }
      });
    }

    if (nextBtn) {
      nextBtn.addEventListener('click', () => {
        if (currentIndex < slides.length - 1) {
          currentIndex += 1;
          updateGallery();
        }
      });
    }

    // Mobile touch-swipe support for galleries
    let touchStartX = 0;
    let touchEndX = 0;

    gallery.addEventListener('touchstart', (e) => {
      if (e.changedTouches && e.changedTouches.length > 0) {
        touchStartX = e.changedTouches[0].screenX;
      }
    }, { passive: true });

    gallery.addEventListener('touchend', (e) => {
      if (e.changedTouches && e.changedTouches.length > 0) {
        touchEndX = e.changedTouches[0].screenX;
        const deltaX = touchStartX - touchEndX;
        if (Math.abs(deltaX) > 40) {
          if (deltaX > 0 && currentIndex < slides.length - 1) {
            currentIndex += 1;
            updateGallery();
          } else if (deltaX < 0 && currentIndex > 0) {
            currentIndex -= 1;
            updateGallery();
          }
        }
      }
    }, { passive: true });

    updateGallery();
  });

  /* ==========================================================================
   * 5. ACCORDION SPECIFICATIONS (.accordion .title-ct)
   * ========================================================================== */
  const accordionHeaders = document.querySelectorAll('.accordion .title-ct');
  accordionHeaders.forEach((header) => {
    header.addEventListener('click', () => {
      const accordion = header.closest('.accordion');
      if (accordion) {
        accordion.classList.toggle('open');
      }
    });
  });

  /* ==========================================================================
   * 6. INTERACTIVE CONFIGURATOR & WHATSAPP / DOSSIER SUBMISSION
   * ========================================================================== */
  const configSelect = document.getElementById('configProgramSelect');
  const configPreviewImg = document.getElementById('configPreviewImg');
  const configPreviewTitle = document.getElementById('configPreviewTitle');
  const configPreviewDesc = document.getElementById('configPreviewDesc');
  const specFinish = document.getElementById('specFinish');
  const specGauge = document.getElementById('specGauge');
  const specDuration = document.getElementById('specDuration');
  const finishPills = document.querySelectorAll('#finishPills .option-pill');

  function updateConfiguratorModel(modelName) {
    const data = MODEL_CONFIG_DATA[modelName];
    if (!data) return;

    if (configSelect) configSelect.value = modelName;
    if (configPreviewImg) configPreviewImg.style.backgroundImage = `url('${data.image}')`;
    if (configPreviewTitle) configPreviewTitle.textContent = modelName;
    if (configPreviewDesc) configPreviewDesc.textContent = data.desc;
    if (specGauge) specGauge.textContent = data.gauge;
    if (specDuration) specDuration.textContent = data.duration;
  }

  if (configSelect) {
    configSelect.addEventListener('change', (e) => {
      updateConfiguratorModel(e.target.value);
    });
  }

  finishPills.forEach((pill) => {
    pill.addEventListener('click', () => {
      finishPills.forEach((p) => p.classList.remove('active'));
      pill.classList.add('active');
      if (specFinish) {
        specFinish.textContent = pill.getAttribute('data-finish');
      }
    });
  });

  const commissionForm = document.getElementById('commissionForm');
  const whatsappDirectBtn = document.getElementById('whatsappDirectBtn');
  const formFeedback = document.getElementById('formFeedback');

  const buildCommissionMessage = () => {
    const program = configSelect ? configSelect.value : 'Cardose GT Super';
    const finish = specFinish ? specFinish.textContent : 'Optical Mirror Gloss';
    const name = document.getElementById('clientName')?.value.trim() || 'Collector';
    const phone = document.getElementById('clientPhone')?.value.trim() || '';
    const email = document.getElementById('clientEmail')?.value.trim() || '';
    const vehicle = document.getElementById('clientVehicle')?.value.trim() || 'Bespoke Vehicle';
    const notes = document.getElementById('clientNotes')?.value.trim() || 'Standard Studio Allocation';

    return `Hello Cardose Automobili Concierge,\n\nI would like to request a private studio allocation:\n• Program: ${program}\n• Surface Finish: ${finish}\n• Vehicle: ${vehicle}\n• Client: ${name} (${phone} / ${email})\n• Notes: ${notes}`;
  };

  if (commissionForm) {
    commissionForm.addEventListener('submit', (e) => {
      e.preventDefault();
      if (formFeedback) {
        formFeedback.style.display = 'block';
        formFeedback.textContent =
          'Your bespoke specification dossier has been registered. A Cardose Atelier Concierge will contact you within 2 hours.';
      }
      commissionForm.reset();
    });
  }

  if (whatsappDirectBtn) {
    whatsappDirectBtn.addEventListener('click', () => {
      const msg = encodeURIComponent(buildCommissionMessage());
      window.open(`https://wa.me/919876543210?text=${msg}`, '_blank');
    });
  }
});
